# ── Main ────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser(description="PoC clustering and visualisation")
    parser.add_argument("--embeddings", type=str, default=None,
                        help="Directory containing *_embeddings.npy files "
                             "(or omit and use --location for multi-backend resolve)")
    parser.add_argument("--location", type=str, default=None,
                        help="Site code (e.g. 2A400); with embedding_io multi-backend load")
    parser.add_argument("--data-dir", type=str, default=None,
                        help="ANALYSIS_OUTPUT root (default from config)")
    parser.add_argument("--backends", type=str, default=None,
                        help="Comma list: birdnet_native,bacpipe,legacy "
                             "(default: auto-resolve)")
    parser.add_argument("--bacpipe-models", type=str, default=None,
                        help="Comma list of bacpipe model folder names under embeddings/bacpipe/")
    parser.add_argument("--date", type=str, default=None,
                        help="Date filter, comma-separated")
    parser.add_argument("--methods", type=str, default="bf_LabIR,bf_SPIR,sa,mono",
                        help="Methods to include")
    parser.add_argument("--min-cluster-size", type=int, default=5,
                        help="HDBSCAN min_cluster_size")
    parser.add_argument("--umap-n-neighbors", type=int, default=30,
                        help="UMAP n_neighbors")
    parser.add_argument("--output", type=str, default=None,
                        help="Output HTML path (default: embeddings dir / poc_dashboard.html)")
    parser.add_argument("--redesign", action="store_true",
                        help="Regenerate HTML from cached results (skips UMAP/HDBSCAN)")
    parser.add_argument("--cache-dir", type=str, default=None,
                        help="Directory for cache files (default: embeddings dir)")
    args = parser.parse_args()

    methods = [m.strip() for m in args.methods.split(",")]
    date_filter = [d.strip() for d in args.date.split(",")] if args.date else None

    # Resolve primary embeddings dir for cache/output defaults
    emb_dir = args.embeddings
    if emb_dir is None and args.location:
        data_root = args.data_dir or ANALYSIS_OUTPUT
        emb_dir = os.path.join(data_root, args.location, "embeddings")
    if emb_dir is None:
        print("❌ Provide --embeddings DIR or --location SITE")
        sys.exit(2)

    cache_dir = args.cache_dir or emb_dir

    # ── Redesign mode: load cache, regenerate HTML ──────────
    if args.redesign:
        cache_path = os.path.join(cache_dir, CACHE_SUFFIX)
        if not os.path.isfile(cache_path):
            print(f"❌ No cache found at {cache_path}")
            print("   Run without --redesign first to compute results and cache them.")
            sys.exit(1)
        print(f"Loading cached results from {cache_path}...")
        umap_2d, y_method, method_names, cluster_labels, stats, emb_dir_c = load_cache(cache_path)
        print(f"  ✓ Loaded {len(umap_2d):,} points, {stats['overview']['n_clusters']} clusters")
        print("Generating HTML dashboard (from cache)...")
        output_path = args.output or os.path.join(emb_dir, "poc_dashboard.html")
        html = generate_html(emb_dir_c, umap_2d, y_method, method_names,
                             cluster_labels, stats)
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(html)
        print(f"\n✅ Dashboard written to: {output_path}  ({len(html):,} bytes)")
        return

    # ── Full computation mode ───────────────────────────────

    print(f"Methods: {methods}")
    if date_filter:
        print(f"Dates: {date_filter}")

    t0 = time.time()
    # Multi-backend resolve when --location set without exclusive single-dir mode
    use_multi = args.location is not None and (
        args.backends is not None
        or args.bacpipe_models is not None
        or args.embeddings is None
    )
    if use_multi:
        from embedding_io import load_location_embeddings

        data_root = args.data_dir or ANALYSIS_OUTPUT
        backends = (
            [b.strip() for b in args.backends.split(",") if b.strip()]
            if args.backends
            else None
        )
        bp_models = (
            [m.strip() for m in args.bacpipe_models.split(",") if m.strip()]
            if args.bacpipe_models
            else None
        )
        packed = load_location_embeddings(
            data_root,
            args.location,
            methods=methods,
            date_filter=date_filter,
            embeddings_path=args.embeddings,
            backends=backends,
            bacpipe_models=bp_models,
        )
        X = packed["X"]
        y_method = packed["y_method"]
        flat_meta = packed["flat_meta"]
        method_names = packed["methods"]
        embeddings = {}  # not used downstream as dict in current flow
        print(f"Sources: {packed['per_source']}")
    else:
        print(f"Loading embeddings from: {emb_dir}")
        embeddings, X, y_method, flat_meta, method_names = load_embeddings(
            emb_dir, methods, date_filter
        )

    if len(X) == 0:
        print("❌ No embeddings found!")
        sys.exit(1)

    total = len(X)
    print(f"Loaded {total:,} embeddings in {time.time() - t0:.1f}s")

    # ── UMAP ──────────────────────────────
    print(f"Running UMAP (n_neighbors={args.umap_n_neighbors})...")
    t1 = time.time()
    umap_2d = run_umap(X, n_neighbors=args.umap_n_neighbors)
    print(f"  ✓ UMAP done in {time.time() - t1:.1f}s")

    # ── HDBSCAN ──────────────────────────────
    print(f"Running HDBSCAN on UMAP 2D (min_cluster_size={args.min_cluster_size})...")
    t2 = time.time()
    cluster_labels = run_hdbscan(umap_2d, min_cluster_size=args.min_cluster_size,
                                 min_samples=max(1, args.min_cluster_size // 2))
    print(f"  ✓ HDBSCAN done in {time.time() - t2:.1f}s")

    # ── Statistics ──────────────────────────────
    print("Computing statistics...")
    stats = compute_stats(X, y_method, method_names, cluster_labels,
                         embeddings=embeddings)
    
    # ── Shared Cluster & Angular Diversity Analysis ──────
    print("Computing shared cluster analysis...")
    shared_analysis = compute_shared_cluster_analysis(
        X, cluster_labels, y_method, method_names, flat_meta
    )
    stats['shared_cluster_analysis'] = shared_analysis
    
    # ── Noise Reference Analysis ──────────────────────
    noise_vectors = load_noise_embeddings(args.embeddings)
    if noise_vectors:
        print("\nComputing noise distance analysis...")
        noise_analysis = compute_noise_distance(
            X, y_method, method_names, cluster_labels, noise_vectors,
            shared_analysis=shared_analysis
        )
        stats['noise_analysis'] = noise_analysis
        print(f"  ✓ Noise distance computed")
    else:
        print("\n  (No noise reference embeddings found — skipping noise analysis)")
        stats['noise_analysis'] = {"available": False}
    
    summary = shared_analysis['summary']
    print(f"\nShared Cluster Stratification:")
    print(f"  Tier 1 (all 4 methods): {summary['tier_1_all_methods']}")
    print(f"  Tier 2 (3 methods):     {summary['tier_2_three_methods']}")
    print(f"  Tier 3 (2 methods):     {summary['tier_3_two_methods']}")
    print(f"  Tier 4 (bf-only):       {summary['tier_4_bf_only']}")
    print(f"  Tier 5 (mono/sa-only):  {summary['tier_5_mono_sa_only']}")
    print(f"  Noise:                  {summary['noise']}")

    print(f"\nOverview:")
    print(f"  Total embeddings: {stats['overview']['total_embeddings']:,}")
    print(f"  Clusters found:   {stats['overview']['n_clusters']}")
    print(f"  Noise:            {stats['overview']['noise_pct']}%")
    print(f"\nPer-method (SNR proxy: ↑ cosine sim = better SNR, ↓ noise% = better SNR):")
    for pm in stats["per_method"]:
        cs = pm.get("cosine_sim", 0)
        print(f"  {pm['method']:>6s}: {pm['n_embeddings']:>6,} embeddings, "
              f"CosSim={cs:.3f}  Noise={pm['noise_pct']:>5.1f}%  "
              f"{pm['n_unique_clusters']} clusters")

    # ── HTML ──────────────────────────────
    print("Generating HTML dashboard...")
    output_path = args.output or os.path.join(args.embeddings, "poc_dashboard.html")
    html = generate_html(args.embeddings, umap_2d, y_method, method_names,
                        cluster_labels, stats)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(html)

    print(f"\n✅ Dashboard written to: {output_path}  ({len(html):,} bytes)")

    # Save cache for future --redesign runs
    try:
        cache_path = os.path.join(cache_dir, CACHE_SUFFIX)
        save_cache(cache_path, args.embeddings, umap_2d, y_method,
                   method_names, cluster_labels, stats)
    except Exception as e:
        print(f"  ⚠️  Cache save failed: {e}")

    print(f"   Total time: {time.time() - t0:.1f}s")


if __name__ == "__main__":
    main()
