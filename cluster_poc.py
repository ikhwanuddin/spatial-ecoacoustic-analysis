def load_embeddings(
    emb_dir: str,
    methods: List[str],
    date_filter: Optional[List[str]] = None,
) -> Tuple[Dict[str, np.ndarray], Dict[str, np.ndarray], Dict[str, List[Dict]]]:
    """Load all embeddings and metadata from *emb_dir*.

    Returns:
        embeddings: dict method → (N, 1024) float32
        methods_per_row: (K,) int8 — method index for each row
        row_meta: list of metadata dicts (1:1 with rows)
    """
    all_emb: Dict[str, List[np.ndarray]] = {m: [] for m in methods}
    all_meta: Dict[str, List[Dict]] = {m: [] for m in methods}

    for fname in sorted(os.listdir(emb_dir)):
        if not fname.endswith("_embeddings.npy"):
            continue
        # Extract date and method from filename: YYYY-MM-DD_METHOD_embeddings.npy
        try:
            parts = fname.replace("_embeddings.npy", "").split("_", 3)
            date_str = parts[0]
            method = "_".join(parts[1:])
        except ValueError:
            continue

        if date_filter and date_str not in date_filter:
            continue
        if method not in methods:
            continue

        emb_path = os.path.join(emb_dir, fname)
        meta_path = emb_path.replace("_embeddings.npy", "_meta.json")

        if not os.path.isfile(emb_path):
            continue

        emb = np.load(emb_path).astype(np.float32)
        if emb.ndim == 1:
            emb = emb.reshape(1, -1)

        meta: List[Dict] = []
        if os.path.isfile(meta_path):
            with open(meta_path, "r") as f:
                meta = json.load(f)

        all_emb[method].append(emb)
        all_meta[method].extend(meta)

        print(f"  {fname}: {len(emb)} embeddings")

    # Concatenate
    embeddings: Dict[str, np.ndarray] = {}
    for m in methods:
        if all_emb[m]:
            embeddings[m] = np.concatenate(all_emb[m], axis=0)
        else:
            embeddings[m] = np.zeros((0, EMBEDDING_DIM), dtype=np.float32)

    # Flatten for clustering
    stacked = []
    method_ids = []
    flat_meta = []
    for i, m in enumerate(methods):
        n = len(embeddings[m])
        if n > 0:
            stacked.append(embeddings[m])
            method_ids.append(np.full(n, i, dtype=np.int8))
            flat_meta.extend(all_meta[m])

    if not stacked:
        return embeddings, np.array([], dtype=np.int8), []

    X = np.concatenate(stacked, axis=0).astype(np.float32)
    y_method = np.concatenate(method_ids)

    return embeddings, X, y_method, flat_meta, methods


# ── Noise Reference ─────────────────────────────────────

def load_noise_embeddings(emb_dir: str) -> Optional[Dict[str, np.ndarray]]:
    """Load noise reference embeddings if available.

    Returns:
        Dict group_name → (N, 1024) mean noise vector per group, or None.
    """
    noise_paths = [
        f for f in os.listdir(emb_dir)
        if f.startswith("noise_") and f.endswith("_embeddings.npy")
    ]
    if not noise_paths:
        return None

    noise_vectors: Dict[str, np.ndarray] = {}
    for fname in noise_paths:
        group = fname.replace("noise_", "").replace("_embeddings.npy", "")
        path = os.path.join(emb_dir, fname)
        emb = np.load(path).astype(np.float32)
        if emb.ndim == 1:
            emb = emb.reshape(1, -1)
        # L2-normalise and compute mean vector
        norms = np.linalg.norm(emb, axis=1, keepdims=True)
        norms = np.where(norms == 0, 1.0, norms)
        emb_norm = emb / norms
        noise_vectors[group] = np.mean(emb_norm, axis=0).astype(np.float32)
        print(f"  noise_{group}: {len(emb)} embeddings → mean vector")

    return noise_vectors


def compute_noise_distance(
    X: np.ndarray,
    y_method: np.ndarray,
    method_names: List[str],
    cluster_labels: np.ndarray,
    noise_vectors: Dict[str, np.ndarray],
    shared_analysis: Optional[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    """Compute cosine similarity of each cluster embedding to noise reference.

    Returns per-cluster and per-method noise similarity stats,
    plus top shared clusters with per-method noise distance breakdown.
    """
    # Map methods to their own noise groups (apples-to-apples comparison)
    # bf_LabIR → noise_LabIR, bf_SPIR → noise_SPIR, sa → noise_sa, mono → noise_mono
    # Omitting a method is fine — SA/Mono noise refs may not exist yet
    method_to_noise: Dict[str, str] = {}
    for method in method_names:
        noise_group = method.replace("bf_", "")  # bf_LabIR→LabIR, bf_SPIR→SPIR, sa→sa, mono→mono
        if noise_group in noise_vectors:
            method_to_noise[method] = noise_group

    if not method_to_noise:
        return {}

    # L2-normalise all embeddings
    norms = np.linalg.norm(X, axis=1, keepdims=True)
    norms = np.where(norms == 0, 1.0, norms)
    X_norm = X / norms

    # Compute noise similarity per embedding
    noise_sim = np.zeros(len(X), dtype=np.float32)
    for i, method in enumerate(method_names):
        mask = y_method == i
        if method in method_to_noise:
            noise_vec = noise_vectors[method_to_noise[method]]
            noise_sim[mask] = np.dot(X_norm[mask], noise_vec)

    # Per-method mean noise similarity
    per_method: List[Dict] = []
    for i, method in enumerate(method_names):
        mask = y_method == i
        if np.sum(mask) > 0:
            mean_sim = float(np.mean(noise_sim[mask]))
            per_method.append({
                "method": method,
                "mean_noise_sim": round(mean_sim, 4),
                "mean_noise_distance": round(1.0 - mean_sim, 4),
            })

    # Per-cluster noise similarity
    per_cluster: List[Dict] = []
    for cid in sorted(set(cluster_labels)):
        if cid == -1:
            continue
        mask = cluster_labels == cid
        if np.sum(mask) > 0:
            mean_sim = float(np.mean(noise_sim[mask]))
            per_cluster.append({
                "cluster_id": int(cid),
                "size": int(np.sum(mask)),
                "mean_noise_sim": round(mean_sim, 4),
                "mean_noise_distance": round(1.0 - mean_sim, 4),
            })

    # ── Top shared clusters with per-method noise distance breakdown ──
    top_shared_clusters: List[Dict] = []
    if shared_analysis is not None:
        # Build cluster_id → tier lookup from shared analysis
        cluster_tier: Dict[int, int] = {}
        for c in shared_analysis.get("clusters", []):
            cluster_tier[c["cluster_id"]] = c["tier"]

        # Process each cluster in tiers 1-3
        for cid in sorted(set(cluster_labels)):
            if cid == -1:
                continue
            tier = cluster_tier.get(cid)
            if tier is None or tier > 3:
                continue

            cluster_mask = cluster_labels == cid
            cluster_size_val = int(np.sum(cluster_mask))
            method_breakdown: List[Dict] = []
            cluster_noise_distances: List[float] = []

            for i, method in enumerate(method_names):
                method_mask = (y_method == i) & cluster_mask
                n_method = int(np.sum(method_mask))
                if n_method > 0:
                    mean_sim = float(np.mean(noise_sim[method_mask]))
                    nd = round(1.0 - mean_sim, 4)
                    method_breakdown.append({
                        "method": method,
                        "n": n_method,
                        "noise_distance": nd,
                    })
                    cluster_noise_distances.append(nd)

            if method_breakdown:
                mean_nd = round(float(np.mean(cluster_noise_distances)), 4)
                top_shared_clusters.append({
                    "cluster_id": int(cid),
                    "size": cluster_size_val,
                    "tier": tier,
                    "mean_noise_distance": mean_nd,
                    "method_breakdown": method_breakdown,
                })

        # Sort by mean noise distance descending, take top 10
        top_shared_clusters.sort(key=lambda c: c["mean_noise_distance"], reverse=True)
        top_shared_clusters = top_shared_clusters[:10]

    return {
        "per_method": per_method,
        "per_cluster": per_cluster,
        "available": True,
        "top_shared_clusters": top_shared_clusters,
    }

# ── UMAP ────────────────────────────────────────────────

def run_umap(X: np.ndarray, n_components: int = 2, n_neighbors: int = 30,
             min_dist: float = 0.1, random_state: int = 42) -> np.ndarray:
    """Reduce *X* to *n_components* dimensions via UMAP."""
    import umap
    import warnings
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        reducer = umap.UMAP(
            n_components=n_components,
            n_neighbors=n_neighbors,
            min_dist=min_dist,
            random_state=random_state,
            n_jobs=1,  # parallelism doesn't work with random_state set; keep 1
            verbose=False,
        )
        return reducer.fit_transform(X)


# ── HDBSCAN ─────────────────────────────────────────────

def run_hdbscan(X: np.ndarray, min_cluster_size: int = 5,
                min_samples: int = 3) -> np.ndarray:
    """Cluster *X* with HDBSCAN.  Returns label array (-1 = noise).

    For speed on real datasets, callers should pass the UMAP 2D
    projection rather than the raw 1024D embeddings.  UMAP preserves
    topological structure, so clusters in 2D ≈ clusters in 1024D.
    """
    import hdbscan
    clusterer = hdbscan.HDBSCAN(
        min_cluster_size=min_cluster_size,
        min_samples=min_samples,
        prediction_data=True,
    )
    return clusterer.fit_predict(X)


def compute_intra_method_cosine(embeddings: Dict[str, np.ndarray],
                                method_names: List[str]) -> List[float]:
    """Compute mean pairwise cosine similarity per method — O(nd).

    Higher values = more consistent acoustic features = better SNR.

    Uses the identity  ∑_{i≠j} x_i·x_j  =  ‖∑x_i‖² - n
    (since each x_i is L2-normalized, self-dot = 1).
    Avoids materialising the O(n²) Gram matrix.
    """
    results = []
    for method in method_names:
        X = embeddings.get(method)
        if X is None or X.shape[0] < 2:
            results.append(0.0)
            continue
        # L2 normalize each row
        norms = np.linalg.norm(X, axis=1, keepdims=True)
        norms = np.where(norms == 0, 1.0, norms)
        X_norm = X / norms
        n = X_norm.shape[0]
        # sum_vec = Σ x_i  →  ‖sum_vec‖² = Σ_{i,j} x_i·x_j
        sum_vec = np.sum(X_norm, axis=0)  # (D,)
        total = float(np.dot(sum_vec, sum_vec))
        mean_cos = (total - n) / (n * (n - 1))
        results.append(round(mean_cos, 4))
    return results


# ── Statistics ──────────────────────────────────────────

def compute_stats(X: np.ndarray, y_method: np.ndarray, method_names: List[str],
                  cluster_labels: np.ndarray,
                  embeddings: Optional[Dict[str, np.ndarray]] = None,
                  ) -> Dict[str, Any]:
    """Compute per-method, per-cluster, and SNR-proxy statistics."""
    stats: Dict[str, Any] = {"per_method": [], "per_cluster": [],
                              "overview": {}, "snr_proxy": {}}

    n_clusters = len(set(cluster_labels)) - (1 if -1 in cluster_labels else 0)
    n_noise = int(np.sum(cluster_labels == -1))

    stats["overview"] = {
        "total_embeddings": int(len(X)),
        "n_clusters": n_clusters,
        "n_noise": n_noise,
        "noise_pct": round(n_noise / max(len(X), 1) * 100, 1),
        "embedding_dim": X.shape[1],
    }

    for i, method in enumerate(method_names):
        mask = y_method == i
        n = int(np.sum(mask))
        labels = cluster_labels[mask]
        n_in_cluster = int(np.sum(labels >= 0))
        n_noise_m = int(np.sum(labels == -1))
        unique_clusters = len(set(labels[labels >= 0]))

        stats["per_method"].append({
            "method": method,
            "n_embeddings": n,
            "n_in_cluster": n_in_cluster,
            "n_noise": n_noise_m,
            "noise_pct": round(n_noise_m / max(n, 1) * 100, 1),
            "n_unique_clusters": unique_clusters,
        })

    # ── SNR Proxy: intra-method cosine similarity ──
    if embeddings is not None:
        cos_sims = compute_intra_method_cosine(embeddings, method_names)
        stats["snr_proxy"] = {
            "cosine_similarity": [
                {"method": m, "value": v}
                for m, v in zip(method_names, cos_sims)
            ],
            "method_order": method_names,
        }
        # Also attach cosine similarity to per-method entries
        for i, v in enumerate(cos_sims):
            stats["per_method"][i]["cosine_sim"] = v

    for cid in sorted(set(cluster_labels)):
        if cid == -1:
            continue
        mask = cluster_labels == cid
        total = int(np.sum(mask))
        by_method = {}
        for i, method in enumerate(method_names):
            m_count = int(np.sum((y_method == i) & mask))
            by_method[method] = m_count
        stats["per_cluster"].append({
            "cluster_id": int(cid),
            "size": total,
            "by_method": by_method,
        })

    return stats


# ── Shared Cluster & Angular Diversity Analysis ──────────

def compute_shared_cluster_analysis(
    X: np.ndarray,
    cluster_labels: np.ndarray,
    y_method: np.ndarray,
    method_names: List[str],
    metadata: List[Dict],
) -> Dict[str, Any]:
    """Analyze shared clusters, angular diversity, and within-cluster coherence.
    
    Returns detailed per-cluster statistics including:
    - Which methods are present in each cluster
    - Within-cluster coherence (cosine similarity) per method
    - Angular diversity (unique azimuths) for beamforming methods
    - Stratification tier (how many methods share this cluster)
    
    Stratification tiers:
    - Tier 1: All 4 methods present (most robust)
    - Tier 2: 3 methods present
    - Tier 3: 2 methods present (shared cluster threshold)
    - Tier 4: Beamforming-only (only bf_LabIR and/or bf_SPIR)
    - Tier 5: Mono-only or SA-only
    """
    analysis = {
        "clusters": [],
        "summary": {
            "tier_1_all_methods": 0,
            "tier_2_three_methods": 0,
            "tier_3_two_methods": 0,
            "tier_4_bf_only": 0,
            "tier_5_mono_sa_only": 0,
            "noise": 0,
        },
        "angular_diversity": {},
    }
    
    # Identify beamforming methods
    bf_methods = {"bf_LabIR", "bf_SPIR"}
    non_bf_methods = set(method_names) - bf_methods
    
    # L2 normalize all embeddings
    norms = np.linalg.norm(X, axis=1, keepdims=True)
    norms = np.where(norms == 0, 1.0, norms)
    X_norm = X / norms
    
    # Analyze each cluster
    for cid in sorted(set(cluster_labels)):
        if cid == -1:
            analysis["summary"]["noise"] = int(np.sum(cluster_labels == -1))
            continue
        
        cluster_mask = cluster_labels == cid
        cluster_indices = np.where(cluster_mask)[0]
        cluster_size = len(cluster_indices)
        
        # Which methods are present?
        methods_present = {}
        for i, method in enumerate(method_names):
            method_mask = (y_method == i) & cluster_mask
            count = int(np.sum(method_mask))
            if count > 0:
                methods_present[method] = count
        
        n_methods = len(methods_present)
        
        # Determine tier
        if n_methods == len(method_names):
            tier = 1
            analysis["summary"]["tier_1_all_methods"] += 1
        elif n_methods == 3:
            tier = 2
            analysis["summary"]["tier_2_three_methods"] += 1
        elif n_methods == 2:
            tier = 3
            analysis["summary"]["tier_3_two_methods"] += 1
        elif all(m in bf_methods for m in methods_present.keys()):
            tier = 4
            analysis["summary"]["tier_4_bf_only"] += 1
        else:
            tier = 5
            analysis["summary"]["tier_5_mono_sa_only"] += 1
        
        # Within-cluster coherence per method
        coherence_per_method = {}
        for method, count in methods_present.items():
            method_mask = np.array([metadata[idx]["method"] == method for idx in cluster_indices])
            method_indices = cluster_indices[method_mask]
            
            if len(method_indices) >= 2:
                X_method = X_norm[method_indices]
                # Mean pairwise cosine similarity
                sum_vec = np.sum(X_method, axis=0)
                total = float(np.dot(sum_vec, sum_vec))
                n = len(method_indices)
                mean_cos = (total - n) / (n * (n - 1))
                coherence_per_method[method] = round(mean_cos, 4)
            else:
                coherence_per_method[method] = None
        
        # Angular diversity (for beamforming methods)
        azimuths = set()
        elevations = set()
        for idx in cluster_indices:
            meta = metadata[idx]
            if meta.get("azimuth") is not None:
                azimuths.add(meta["azimuth"])
            if meta.get("elevation") is not None:
                elevations.add(meta["elevation"])
        
        angular_diversity = {
            "unique_azimuths": len(azimuths),
            "azimuths": sorted(list(azimuths)) if azimuths else [],
            "unique_elevations": len(elevations),
            "elevations": sorted(list(elevations)) if elevations else [],
        }
        
        # Store in angular_diversity dict for plotting
        if angular_diversity["unique_azimuths"] > 0:
            analysis["angular_diversity"][int(cid)] = angular_diversity["azimuths"]
        
        # Build cluster record
        cluster_record = {
            "cluster_id": int(cid),
            "size": cluster_size,
            "tier": tier,
            "methods_present": methods_present,
            "n_methods": n_methods,
            "coherence_per_method": coherence_per_method,
            "angular_diversity": angular_diversity,
        }
        analysis["clusters"].append(cluster_record)
    
    return analysis



